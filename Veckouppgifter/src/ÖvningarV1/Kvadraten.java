package ÖvningarV1;

public class Kvadraten {
    public static void main(String[] args) {

        /*Skapa ett program som skriver ut kvadraten på ett tal som är definierat i en variabel.
        Kvadraten är talet multiplicerat med sig själv.
        */

        int tal = 6;
        int kvadraten = tal*tal;
        System.out.println("Talet är: " + tal);
        System.out.println("Kvadraten av talet är: " + kvadraten);
    }
}
